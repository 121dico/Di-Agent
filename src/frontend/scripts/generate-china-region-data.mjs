import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { geoMercator, geoPath } from 'd3-geo';

const here = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(here, '..');
const provinceCollection = JSON.parse(await readFile(resolve(frontendRoot, 'node_modules/cn-atlas/provinces.json'), 'utf8'));
const cityRecords = JSON.parse(await readFile(resolve(frontendRoot, 'node_modules/province-city-china/dist/city.json'), 'utf8'));
const directProvinceCodes = new Set(['110000', '120000', '310000', '500000', '710000', '810000', '820000']);

// The source uses planar GeoJSON winding. D3's spherical projections expect
// the opposite ring direction, otherwise the complement of China is fitted.
for (const feature of provinceCollection.features) {
  const geometry = feature.geometry;
  if (geometry.type === 'Polygon') {
    geometry.coordinates = geometry.coordinates.map((ring) => [...ring].reverse());
  } else if (geometry.type === 'MultiPolygon') {
    geometry.coordinates = geometry.coordinates.map((polygon) => polygon.map((ring) => [...ring].reverse()));
  }
}

const projection = geoMercator().fitExtent([[18, 18], [522, 384]], provinceCollection);
const toPath = geoPath(projection).digits(1);

const regions = provinceCollection.features.map((feature) => {
  const code = feature.properties['区划码'];
  const name = feature.properties['地名'];
  const prefix = code.slice(0, 2);
  const cities = directProvinceCodes.has(code)
    ? [name]
    : cityRecords.filter((city) => city.province === prefix).map((city) => city.name);
  return { code, name, path: toPath(feature), direct: directProvinceCodes.has(code), cities };
});

if (regions.length !== 34 || !regions.some((region) => region.name === '台湾省')) {
  throw new Error('China region source must contain all 34 province-level regions including Taiwan');
}

const output = `// Generated by scripts/generate-china-region-data.mjs. Do not edit by hand.\n` +
  `export interface ChinaRegion { code: string; name: string; path: string; direct: boolean; cities: string[] }\n\n` +
  `export const chinaRegions: ChinaRegion[] = ${JSON.stringify(regions)};\n`;

await writeFile(resolve(frontendRoot, 'src/components/report/chinaRegionData.ts'), output);
console.log(`Generated ${regions.length} regions and ${regions.reduce((sum, region) => sum + region.cities.length, 0)} city entries.`);
